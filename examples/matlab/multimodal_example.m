% Process several modalities through one Recording and shared phase model.
% See eda_example.m for EDA, which requires the optional cvxEDA dependency.

showPlots = true;

exampleDirectory = fileparts(mfilename('fullpath'));
repositoryRoot = fileparts(fileparts(exampleDirectory));
addpath(genpath(fullfile(repositoryRoot,'matlab')))

dataFile = fullfile(repositoryRoot,'examples','sample_data', ...
    'synthetic_multimodal_180s.hdf5');
recording = mpk.io.readBioSignalsPluxHdf5( ...
    dataFile, ...
    'FnirsColumnOrder',[1 2]);

phaseIntervals = [0 60 120;60 120 180];
phaseLabels = {'baseline','task_1','task_2'};
recording.setPhases(phaseIntervals,phaseLabels);

results = struct();
temperatureProcessor = mpk.TemperatureProcessor();
temperatureProcessor.ShowPlots = showPlots;
results.Temperature = recording.processPhases( ...
    temperatureProcessor, ...
    'temp');
respirationProcessor = mpk.RespirationProcessor();
respirationProcessor.ShowPlots = showPlots;
results.Respiration = recording.processPhases( ...
    respirationProcessor, ...
    'rip');

if showPlots
    mpk.utils.plotSignalWithPhases( ...
        recording.getSignal('ecg'), ...
        recording.PhaseIntervalsSeconds, ...
        'PhaseLabels',recording.PhaseLabels, ...
        'Title','Raw ECG with analysis phases');
    mpk.utils.plotSignalWithPhases( ...
        recording.getSignal('fnirs_red'), ...
        recording.PhaseIntervalsSeconds, ...
        'PhaseLabels',recording.PhaseLabels, ...
        'Title','fNIRS red current');
    mpk.utils.plotSignalWithPhases( ...
        recording.getSignal('fnirs_infrared'), ...
        recording.PhaseIntervalsSeconds, ...
        'PhaseLabels',recording.PhaseLabels, ...
        'Title','fNIRS infrared current');
end

results.ECG = recording.processPhases( ...
    mpk.ECGProcessor( ...
        'LabelFrequencyAnalysis',1, ...
        'ReturnIntermediates',true), ...
    'ecg');

fnirsProcessor = mpk.FNIRSProcessor('AgeYears',25);
baselineRed = recording.extractPhase('fnirs_red','baseline');
baselineInfrared = recording.extractPhase( ...
    'fnirs_infrared', ...
    'baseline');
fnirsBaseline = fnirsProcessor.computeBaselineValues( ...
    baselineRed, ...
    baselineInfrared);
results.FNIRS = recording.processPhases( ...
    fnirsProcessor, ...
    {'fnirs_red','fnirs_infrared'}, ...
    'Phases',{'task_1','task_2'}, ...
    'ProcessArguments',{ ...
        'BaselineRedValue',fnirsBaseline.RedValue, ...
        'BaselineInfraredValue',fnirsBaseline.InfraredValue});

