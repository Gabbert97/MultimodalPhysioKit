    signal,intervals, ...
    'PhaseLabels',{'only_one'}), ...
    'mpk:utils:plotSignalWithPhases:PhaseLabelMismatch')

verifyError(testCase,@() mpk.utils.plotSignalWithPhases( ...
    signal,intervals, ...
    'PhaseLabels',{'valid',''}), ...
    'mpk:utils:plotSignalWithPhases:InvalidPhaseLabels')
end

function signal = localSignal(startTime)
fs = 10;

time = startTime + (0:99)'/fs;
samples = sin(2*pi*0.5*(time-startTime));

signal = mpk.Signal( ...
    samples, ...
    time, ...
    fs, ...
    'ecg', ...
    'mV');
end

function closeIfValid(figureHandle)
if isgraphics(figureHandle,'figure')
    close(figureHandle)
end
end