function tests = test_utils_plot_signal_with_phases
tests = functiontests(localfunctions);
end

function setupOnce(testCase)
repositoryRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
testCase.TestData.OriginalPath = path;
addpath(genpath(fullfile(repositoryRoot,'matlab')))
end

function teardownOnce(testCase)
path(testCase.TestData.OriginalPath)
close all force
end

function testUsesExactTemporalBoundariesAndLabels(testCase)
signal = localSignal(4.2);
intervals = [4.25 6.4;5.75 8.05];
labels = {'first','second'};

[figureHandle,axesHandle] = mpk.utils.plotSignalWithPhases( ...
    signal,intervals, ...
    'PhaseLabels',labels, ...
    'FigureVisible',false);

cleanup = onCleanup(@() closeIfValid(figureHandle));

patches = findall(axesHandle,'Type','patch');
verifyEqual(testCase,numel(patches),2)

patchStarts = sort(reshape( ...
    arrayfun(@(item) min(item.XData),patches), ...
    1,[]));

patchEnds = sort(reshape( ...
    arrayfun(@(item) max(item.XData),patches), ...
    1,[]));

expectedStarts = sort(reshape(intervals(1,:),1,[]));
expectedEnds = sort(reshape(intervals(2,:),1,[]));

verifyEqual( ...
    testCase, ...
    patchStarts, ...
    expectedStarts, ...
    'AbsTol',0)

verifyEqual( ...
    testCase, ...
    patchEnds, ...
    expectedEnds, ...
    'AbsTol',0)

startLines = findall(axesHandle,'Type','line','LineStyle','--');
endLines = findall(axesHandle,'Type','line','LineStyle',':');

actualStartLines = sort(reshape( ...
    arrayfun(@(item) item.XData(1),startLines), ...
    1,[]));

actualEndLines = sort(reshape( ...
    arrayfun(@(item) item.XData(1),endLines), ...
    1,[]));

verifyEqual( ...
    testCase, ...
    actualStartLines, ...
    expectedStarts, ...
    'AbsTol',0)

verifyEqual( ...
    testCase, ...
    actualEndLines, ...
    expectedEnds, ...
    'AbsTol',0)

texts = findall(axesHandle,'Type','text');
phaseTexts = texts(ismember({texts.String},labels));

verifyEqual( ...
    testCase, ...
    sort({phaseTexts.String}), ...
    sort(labels))

actualTextPositions = sort(reshape( ...
    arrayfun(@(item) item.Position(1),phaseTexts), ...
    1,[]));

expectedTextPositions = sort(reshape(mean(intervals,1),1,[]));

verifyEqual( ...
    testCase, ...
    actualTextPositions, ...
    expectedTextPositions, ...
    'AbsTol',0)
end

function testOmittedLabelsAndDisabledLabels(testCase)
signal = localSignal(0);
intervals = [0 3;2 5];

[figureHandle,axesHandle] = mpk.utils.plotSignalWithPhases( ...
    signal,intervals, ...
    'FigureVisible',false);

cleanup = onCleanup(@() closeIfValid(figureHandle));

verifyEqual( ...
    testCase, ...
    numel(findall(axesHandle,'Type','patch')), ...
    2)

[secondFigure,secondAxes] = mpk.utils.plotSignalWithPhases( ...
    signal,intervals, ...
    'PhaseLabels',{'a','b'}, ...
    'ShowPhaseLabels',false, ...
    'FigureVisible',false);

secondCleanup = onCleanup(@() closeIfValid(secondFigure));

verifyEmpty(testCase,findall(secondAxes,'Type','text','String','a'))
verifyEmpty(testCase,findall(secondAxes,'Type','text','String','b'))
end

