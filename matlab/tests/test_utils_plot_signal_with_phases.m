verifyEqual(testCase,numel(findall(axesHandle,'Type','line')),1)
end

function testParentAxesHiddenFigureAndHoldRestoration(testCase)
figureHandle = figure('Visible','off');
cleanup = onCleanup(@() closeIfValid(figureHandle));

parentAxes = axes('Parent',figureHandle);

hold(parentAxes,'on')

[returnedFigure,returnedAxes] = ...
    mpk.utils.plotSignalWithPhases( ...
        localSignal(0), ...
        [0;2], ...
        'ParentAxes',parentAxes);

verifyEqual(testCase,returnedFigure,figureHandle)
verifyEqual(testCase,returnedAxes,parentAxes)
verifyTrue(testCase,ishold(parentAxes))

hold(parentAxes,'off')

mpk.utils.plotSignalWithPhases( ...
    localSignal(0), ...
    [2;4], ...
    'ParentAxes',parentAxes);

verifyFalse(testCase,ishold(parentAxes))

[hiddenFigure,~] = mpk.utils.plotSignalWithPhases( ...
    localSignal(0), ...
    [0;2], ...
    'FigureVisible',false);

hiddenCleanup = onCleanup(@() closeIfValid(hiddenFigure));

verifyEqual( ...
    testCase, ...
    char(hiddenFigure.Visible), ...
    'off')
end

function testNonzeroStartOverlapAndFinalExclusiveEnd(testCase)
signal = localSignal(4.2);

signalStopExclusive = ...
    signal.Time(end) + 1/signal.SamplingFrequency;

intervals = [ ...
    4.2 5.0; ...
    6.5 signalStopExclusive];

[figureHandle,axesHandle] = mpk.utils.plotSignalWithPhases( ...
    signal,intervals, ...
    'PhaseLabels',{'overlap_1','overlap_2'}, ...
    'FigureVisible',false);

cleanup = onCleanup(@() closeIfValid(figureHandle));

patches = findall(axesHandle,'Type','patch');

allEnds = arrayfun( ...
    @(item) max(item.XData), ...
    patches);

verifyTrue(testCase,any(allEnds == signalStopExclusive))
end

function testRejectsInvalidSignalAndIntervals(testCase)
signal = localSignal(0);

verifyError(testCase,@() mpk.utils.plotSignalWithPhases( ...
    signal.Samples,[0;1]), ...
    'mpk:utils:plotSignalWithPhases:InvalidSignal')

invalidIntervals = { ...
    [0 1 2], ...
    complex([0;1],[0;1]), ...
    [0;Inf], ...
    [-1;1], ...
    [1;1], ...
    [2;1]};

for index = 1:numel(invalidIntervals)
    verifyError(testCase,@() mpk.utils.plotSignalWithPhases( ...
        signal,invalidIntervals{index}), ...
        'mpk:utils:plotSignalWithPhases:InvalidPhaseIntervals')
end
end

function testRejectsIntervalsOutsideSignal(testCase)
signal = localSignal(4.2);

stop = signal.Time(end) + 1/signal.SamplingFrequency;

verifyError(testCase,@() mpk.utils.plotSignalWithPhases( ...
    signal,[4.1;5]), ...
    'mpk:utils:plotSignalWithPhases:PhaseOutsideSignal')

verifyError(testCase,@() mpk.utils.plotSignalWithPhases( ...
    signal,[5;stop + 0.01]), ...
    'mpk:utils:plotSignalWithPhases:PhaseOutsideSignal')
end

function testRejectsInvalidLabels(testCase)
