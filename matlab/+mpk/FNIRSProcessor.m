classdef FNIRSProcessor
    %FNIRSPROCESSOR Process one synchronized dual-wavelength Signal pair.
    %
    % Each supplied red/infrared pair is one complete, independent analysis
    % window. The validated procedural fNIRS pipeline remains the scientific
    % implementation; this class only validates, delegates, and packages.

    properties
        AgeYears
        ReturnIntermediates
    end

    methods
        function obj = FNIRSProcessor(varargin)
            parser = inputParser;
            parser.FunctionName = 'mpk.FNIRSProcessor';
            addParameter(parser,'AgeYears',[]);
            addParameter(parser,'ReturnIntermediates',false);
            parse(parser,varargin{:});

            mpk.FNIRSProcessor.validateAge(parser.Results.AgeYears);
            mpk.FNIRSProcessor.validateReturnIntermediates( ...
                parser.Results.ReturnIntermediates);
            obj.AgeYears = parser.Results.AgeYears;
            obj.ReturnIntermediates = parser.Results.ReturnIntermediates;
        end

        function result = process(obj,redSignal,infraredSignal,varargin)
            %PROCESS Process exactly one supplied synchronized Signal pair.
            if nargin < 2 || ~isa(redSignal,'mpk.Signal')
                error('mpk:FNIRSProcessor:InvalidRedSignal', ...
                    'redSignal must be an mpk.Signal instance.')
            end
            if nargin < 3 || ~isa(infraredSignal,'mpk.Signal')
                error('mpk:FNIRSProcessor:InvalidInfraredSignal', ...
                    'infraredSignal must be an mpk.Signal instance.')
            end

            [features,proceduralIntermediates,options] = ...
                obj.runPipeline(redSignal,infraredSignal,varargin{:});

            if obj.ReturnIntermediates
                intermediates = proceduralIntermediates;
            else
                intermediates = struct();
            end

            redLabel = redSignal.Label;
            if isempty(redLabel)
                redLabel = 'fnirs_red';
            end
            infraredLabel = infraredSignal.Label;
            if isempty(infraredLabel)
                infraredLabel = 'fnirs_infrared';
            end
            sourceLabels = {redLabel,infraredLabel};

            resultOptions = struct( ...
                'AgeYears',obj.AgeYears, ...
                'ReturnIntermediates',obj.ReturnIntermediates, ...
                'BaselineRedValue',options.BaselineRedValue, ...
                'BaselineInfraredValue', ...
                    options.BaselineInfraredValue);
            metadata = struct( ...
                'source','process_fnirs', ...
                'age_years',obj.AgeYears, ...
                'original_sampling_frequency', ...
                    redSignal.SamplingFrequency, ...
                'processed_sampling_frequency', ...
                    proceduralIntermediates. ...
                    processed_sampling_frequency, ...
                'original_n_samples',redSignal.count(), ...
                'processed_n_samples', ...
                    numel(proceduralIntermediates.downsampled_time), ...
                'start_time_seconds',redSignal.Time(1), ...
                'end_time_seconds',redSignal.Time(end), ...
                'baseline_mode', ...
                    proceduralIntermediates.baseline_mode, ...
                'baseline_red_value', ...
                    proceduralIntermediates.baseline_red_value, ...
                'baseline_infrared_value', ...
                    proceduralIntermediates.baseline_infrared_value, ...
                'analysis_scope','single_signal_pair');

            result = mpk.ProcessingResult( ...
                'fnirs', ...
                'process_fnirs', ...
                features, ...
                sourceLabels, ...
                resultOptions, ...
                metadata, ...
                intermediates);
        end

        function data = downsampleCurrents(obj,redSignal,infraredSignal)
            %DOWNSAMPLECURRENTS Apply validated moving-average downsampling.
            obj.validateSignalPair(redSignal,infraredSignal);
            processedSamplingFrequency = 10;
            fullSignalPhase = [1; redSignal.count()];
            shiftedTime = redSignal.Time - redSignal.Time(1);

            [infrared,~,~] = downsampling( ...
                infraredSignal.Samples,shiftedTime, ...
                redSignal.SamplingFrequency, ...
                processedSamplingFrequency,fullSignalPhase,false);
            [red,time,~] = downsampling( ...
                redSignal.Samples,shiftedTime, ...
                redSignal.SamplingFrequency, ...
                processedSamplingFrequency,fullSignalPhase,false);
            data = struct( ...
                'Red',red, ...
                'Infrared',infrared, ...
                'Time',time, ...
                'SamplingFrequency',processedSamplingFrequency, ...
                'DownsamplingFactor', ...
                    redSignal.SamplingFrequency / ...
                    processedSamplingFrequency);
        end

        function data = extractDownsampledCurrents( ...
                obj,redSignal,infraredSignal)
            %EXTRACTDOWNSAMPLEDCURRENTS Alias of downsampleCurrents.
            data = obj.downsampleCurrents(redSignal,infraredSignal);
        end

        function data = filterCurrents(obj,redSignal,infraredSignal)
            %FILTERCURRENTS Apply validated downsampling and current LPFs.
            obj.validateSignalPair(redSignal,infraredSignal);
            currentData = fnirs_preprocess_currents( ...
                redSignal.Samples,infraredSignal.Samples, ...
                redSignal.Time,redSignal.SamplingFrequency, ...
                [1; redSignal.count()]);
            data = struct( ...
                'Red',currentData.FilteredRed, ...
                'Infrared',currentData.FilteredInfrared, ...
                'Time',currentData.Time, ...
                'SamplingFrequency',currentData.SamplingFrequency, ...
                'DownsamplingFactor',currentData.DownsamplingFactor, ...
                'DownsampledRed',currentData.DownsampledRed, ...
                'DownsampledInfrared', ...
                    currentData.DownsampledInfrared);
        end

        function data = extractFilteredCurrents( ...
                obj,redSignal,infraredSignal)
            %EXTRACTFILTEREDCURRENTS Alias of filterCurrents.
            data = obj.filterCurrents(redSignal,infraredSignal);
        end

        function baseline = computeBaselineValues( ...
                obj,redSignal,infraredSignal)
            %COMPUTEBASELINEVALUES Compute reusable self-baseline scalars.
            obj.validateSignalPair(redSignal,infraredSignal);
            [redValue,infraredValue,diagnostics] = ...
                fnirs_compute_baseline_values( ...
                    redSignal.Samples, ...
                    infraredSignal.Samples, ...
                    redSignal.Time, ...
                    redSignal.SamplingFrequency);
            baseline = struct( ...
                'RedValue',redValue, ...
                'InfraredValue',infraredValue, ...
                'Mode','self', ...
                'Diagnostics',diagnostics);
        end

        function concentration = computeConcentrationChanges( ...
                obj,redSignal,infraredSignal,varargin)
            %COMPUTECONCENTRATIONCHANGES Convert one current pair to Hb data.
            obj.validateConfiguration();
            obj.validateSignalPair(redSignal,infraredSignal);
            options = mpk.FNIRSProcessor.parseBaselineOptions(varargin{:});
            currentData = fnirs_preprocess_currents( ...
                redSignal.Samples,infraredSignal.Samples, ...
                redSignal.Time,redSignal.SamplingFrequency, ...
                [1; redSignal.count()]);
            [oxy,deoxy,baseline] = LambertBeer( ...
                currentData.FilteredRed, ...
                currentData.FilteredInfrared, ...
                currentData.Time, ...
                currentData.SamplingFrequency, ...
                currentData.PhaseIndexes, ...
                obj.AgeYears, ...
                false, ...
                'BaselineRedValue',options.BaselineRedValue, ...
                'BaselineInfraredValue', ...
                    options.BaselineInfraredValue);
            concentration = struct( ...
                'Oxy',oxy, ...
                'Deoxy',deoxy, ...
                'Time',currentData.Time, ...
                'SamplingFrequency',currentData.SamplingFrequency, ...
                'BaselineMode',baseline.Mode, ...
                'BaselineRedValue',baseline.RedValue, ...
                'BaselineInfraredValue',baseline.InfraredValue, ...
                'FilteredRed',currentData.FilteredRed, ...
                'FilteredInfrared',currentData.FilteredInfrared);
        end

        function concentration = extractConcentrationChanges( ...
                obj,redSignal,infraredSignal,varargin)
            %EXTRACTCONCENTRATIONCHANGES Alias of computeConcentrationChanges.
            concentration = obj.computeConcentrationChanges( ...
                redSignal,infraredSignal,varargin{:});
        end

        function features = extractFeatures( ...
                obj,redSignal,infraredSignal,varargin)
            %EXTRACTFEATURES Return procedural oxy/deoxy feature groups.
            [features,~,~] = obj.runPipeline( ...
                redSignal,infraredSignal,varargin{:});
        end
    end

    methods (Access = private)
        function [features,intermediates,options] = runPipeline( ...
                obj,redSignal,infraredSignal,varargin)
            obj.validateConfiguration();
            obj.validateSignalPair(redSignal,infraredSignal);
            options = mpk.FNIRSProcessor.parseBaselineOptions(varargin{:});
            fullSignalPhase = [1; redSignal.count()];
            [featuresOxy,featuresDeoxy,intermediates] = ...
                fNIRS_signal_processing( ...
                    redSignal.Samples, ...
                    infraredSignal.Samples, ...
                    redSignal.Time, ...
                    redSignal.SamplingFrequency, ...
                    fullSignalPhase, ...
                    obj.AgeYears, ...
                    false, ...
                    'BaselineRedValue',options.BaselineRedValue, ...
                    'BaselineInfraredValue', ...
                        options.BaselineInfraredValue);
            features = struct( ...
                'Oxy',{featuresOxy}, ...
                'Deoxy',{featuresDeoxy});
        end

        function validateConfiguration(obj)
            mpk.FNIRSProcessor.validateAge(obj.AgeYears);
            mpk.FNIRSProcessor.validateReturnIntermediates( ...
                obj.ReturnIntermediates);
        end

        function validateSignalPair(~,redSignal,infraredSignal)
            if ~isa(redSignal,'mpk.Signal')
                error('mpk:FNIRSProcessor:InvalidRedSignal', ...
                    'redSignal must be an mpk.Signal instance.')
            end
            if ~isa(infraredSignal,'mpk.Signal')
                error('mpk:FNIRSProcessor:InvalidInfraredSignal', ...
                    'infraredSignal must be an mpk.Signal instance.')
            end
            if redSignal.count() ~= infraredSignal.count()
                error('mpk:FNIRSProcessor:LengthMismatch', ...
                    'Red and infrared signals must have equal lengths.')
            end
            if redSignal.SamplingFrequency ~= ...
                    infraredSignal.SamplingFrequency
                error('mpk:FNIRSProcessor:SamplingFrequencyMismatch', ...
                    ['Red and infrared signals must have the same ' ...
                     'sampling frequency.'])
            end
            if ~isequal(redSignal.Time,infraredSignal.Time) || ...
                    any(~isfinite(redSignal.Time(:))) || ...
                    any(diff(redSignal.Time(:)) <= 0)
                error('mpk:FNIRSProcessor:TimeMismatch', ...
                    ['Red and infrared signals must have identical finite ' ...
                     'strictly increasing time vectors.'])
            end
            if ~isnumeric(redSignal.Samples) || ...
                    ~isnumeric(infraredSignal.Samples) || ...
                    ~isreal(redSignal.Samples) || ...
                    ~isreal(infraredSignal.Samples) || ...
                    isempty(redSignal.Samples) || ...
                    isempty(infraredSignal.Samples) || ...
                    any(~isfinite(redSignal.Samples(:))) || ...
                    any(~isfinite(infraredSignal.Samples(:))) || ...
                    any(redSignal.Samples(:) <= 0) || ...
                    any(infraredSignal.Samples(:) <= 0)
                error('mpk:FNIRSProcessor:InvalidCurrentSamples', ...
                    ['Both fNIRS current Signals must contain positive ' ...
                     'finite real numeric samples.'])
            end
            samplingFrequency = redSignal.SamplingFrequency;
            if ~isnumeric(samplingFrequency) || ...
                    ~isreal(samplingFrequency) || ...
                    ~isscalar(samplingFrequency) || ...
                    ~isfinite(samplingFrequency) || ...
                    samplingFrequency <= 0 || ...
                    mod(samplingFrequency,10) ~= 0
                error('mpk:FNIRSProcessor:InvalidSamplingFrequency', ...
                    ['Signal sampling frequency must be a positive ' ...
                     'integer multiple of 10 Hz.'])
            end
        end
    end

    methods (Static, Access = private)
        function validateAge(value)
            if ~isnumeric(value) || islogical(value) || ~isreal(value) || ...
                    ~isscalar(value) || ~isfinite(value) || value <= 0
                error('mpk:FNIRSProcessor:InvalidAge', ...
                    'AgeYears must be a positive finite real numeric scalar.')
            end
        end

        function validateReturnIntermediates(value)
            if ~islogical(value) || ~isscalar(value)
                error('mpk:FNIRSProcessor:InvalidReturnIntermediates', ...
                    'ReturnIntermediates must be a logical scalar.')
            end
        end

        function options = parseBaselineOptions(varargin)
            parser = inputParser;
            parser.FunctionName = 'mpk.FNIRSProcessor.process';
            addParameter(parser,'BaselineRedValue',[]);
            addParameter(parser,'BaselineInfraredValue',[]);
            parse(parser,varargin{:});
            options = parser.Results;

            redProvided = ~isempty(options.BaselineRedValue);
            infraredProvided = ~isempty(options.BaselineInfraredValue);
            if xor(redProvided,infraredProvided)
                error('mpk:FNIRSProcessor:IncompleteBaselinePair', ...
                    ['BaselineRedValue and BaselineInfraredValue must ' ...
                     'be supplied together.'])
            end
            if redProvided
                mpk.FNIRSProcessor.validateBaselineValue( ...
                    options.BaselineRedValue, ...
                    'mpk:FNIRSProcessor:InvalidBaselineRedValue', ...
                    'BaselineRedValue');
                mpk.FNIRSProcessor.validateBaselineValue( ...
                    options.BaselineInfraredValue, ...
                    'mpk:FNIRSProcessor:InvalidBaselineInfraredValue', ...
                    'BaselineInfraredValue');
            end
        end

        function validateBaselineValue(value,errorIdentifier,argumentName)
            if ~isnumeric(value) || islogical(value) || ~isreal(value) || ...
                    ~isscalar(value) || ~isfinite(value) || value <= 0
                error(errorIdentifier, ...
                    '%s must be a positive finite real numeric scalar.', ...
                    argumentName)
            end
        end
    end
end
