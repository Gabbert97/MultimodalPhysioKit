classdef TemperatureProcessor
    %TEMPERATUREPROCESSOR Extract features from one temperature Signal.
    %
    % PROCESSOR = mpk.TemperatureProcessor() creates a reusable processor
    % with diagnostic plotting disabled. PROCESSOR.PROCESS(SIGNAL) applies
    % the validated procedural temperature pipeline to exactly the supplied
    % mpk.Signal and returns one mpk.ProcessingResult.

    properties
        ShowPlots
    end

    methods
        function obj = TemperatureProcessor()
            obj.ShowPlots = false;
        end

        function result = process(obj,signal)
            %PROCESS Extract skin-temperature features from one Signal.
            if ~isa(signal,'mpk.Signal')
                error('mpk:TemperatureProcessor:InvalidSignal', ...
                    'signal must be an mpk.Signal instance.')
            end
            if ~islogical(obj.ShowPlots) || ~isscalar(obj.ShowPlots)
                error('mpk:TemperatureProcessor:InvalidShowPlots', ...
                    'ShowPlots must be a logical scalar.')
            end

            fullSignalPhase = [1; signal.count()];
            features = temperature_signal_processing( ...
                signal.Samples, ...
                signal.Time, ...
                fullSignalPhase, ...
                signal.SamplingFrequency, ...
                obj.ShowPlots);

            options = struct('ShowPlots',obj.ShowPlots);
            metadata = struct( ...
                'LegacyFunction','temperature_signal_processing', ...
                'SamplingFrequency',signal.SamplingFrequency, ...
                'NumberOfSamples',signal.count(), ...
                'StartTimeSeconds',signal.Time(1), ...
                'EndTimeSeconds',signal.Time(end));
            result = mpk.ProcessingResult( ...
                'Temperature', ...
                'mpk.TemperatureProcessor', ...
                features, ...
                signal.Label, ...
                options, ...
                metadata);
        end
    end
end
