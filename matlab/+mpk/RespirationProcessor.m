classdef RespirationProcessor
    %RESPIRATIONPROCESSOR Extract features from one respiration Signal.
    %
    % PROCESSOR = mpk.RespirationProcessor() creates a reusable processor
    % with diagnostic plotting disabled. PROCESSOR.PROCESS(SIGNAL) applies
    % the validated procedural respiration pipeline to exactly the supplied
    % mpk.Signal and returns one mpk.ProcessingResult.

    properties
        ShowPlots
    end

    methods
        function obj = RespirationProcessor()
            obj.ShowPlots = false;
        end

        function result = process(obj,signal)
            %PROCESS Extract respiration features from one Signal.
            if ~isa(signal,'mpk.Signal')
                error('mpk:RespirationProcessor:InvalidSignal', ...
                    'signal must be an mpk.Signal instance.')
            end
            if ~islogical(obj.ShowPlots) || ~isscalar(obj.ShowPlots)
                error('mpk:RespirationProcessor:InvalidShowPlots', ...
                    'ShowPlots must be a logical scalar.')
            end

            fullSignalPhase = [1; signal.count()];
            features = respiration_signal_processing( ...
                signal.Samples, ...
                signal.Time, ...
                fullSignalPhase, ...
                signal.SamplingFrequency, ...
                obj.ShowPlots);

            downsampleFactor = signal.SamplingFrequency / 100;
            options = struct('ShowPlots',obj.ShowPlots);
            metadata = struct( ...
                'LegacyFunction','respiration_signal_processing', ...
                'OriginalSamplingFrequency',signal.SamplingFrequency, ...
                'ProcessedSamplingFrequency',100, ...
                'OriginalNumberOfSamples',signal.count(), ...
                'ProcessedNumberOfSamples', ...
                    ceil(signal.count() / downsampleFactor), ...
                'StartTimeSeconds',signal.Time(1), ...
                'EndTimeSeconds',signal.Time(end));
            result = mpk.ProcessingResult( ...
                'Respiration', ...
                'mpk.RespirationProcessor', ...
                features, ...
                signal.Label, ...
                options, ...
                metadata);
        end
    end
end
