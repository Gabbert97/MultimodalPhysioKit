classdef EDAProcessor
    %EDAPROCESSOR Object-facing adapter for canonical MATLAB EDA processing.

    properties
        CvxedaPath
        DecompositionCallable
        CacheDirectory
        OutputLabel
        MinimumScrAmplitude
    end

    methods
        function obj = EDAProcessor(varargin)
            parser = inputParser;
            parser.FunctionName = 'mpk.EDAProcessor';
            addParameter(parser,'CvxedaPath','');
            addParameter(parser,'DecompositionCallable',[]);
            addParameter(parser,'CacheDirectory','');
            addParameter(parser,'OutputLabel','eda');
            addParameter(parser,'MinimumScrAmplitude',0.01);
            parse(parser,varargin{:});

            obj.CvxedaPath = mpk.EDAProcessor.normalizeOptionalText( ...
                parser.Results.CvxedaPath,'CvxedaPath');
            callable = parser.Results.DecompositionCallable;
            if ~(isempty(callable) || isa(callable,'function_handle'))
                error('mpk:EDAProcessor:InvalidDecompositionCallable', ...
                    'DecompositionCallable must be empty or a function handle.')
            end
            obj.DecompositionCallable = callable;
            obj.CacheDirectory = mpk.EDAProcessor.normalizeOptionalText( ...
                parser.Results.CacheDirectory,'CacheDirectory');
            obj.OutputLabel = mpk.EDAProcessor.normalizeRequiredText( ...
                parser.Results.OutputLabel,'OutputLabel');
            minimumScrAmplitude = parser.Results.MinimumScrAmplitude;
            if ~isnumeric(minimumScrAmplitude) || ~isreal(minimumScrAmplitude) || ...
                    ~isscalar(minimumScrAmplitude) || ...
                    ~isfinite(minimumScrAmplitude) || minimumScrAmplitude < 0
                error('mpk:EDAProcessor:InvalidMinimumScrAmplitude', ...
                    ['MinimumScrAmplitude must be a finite numeric scalar ' ...
                     'greater than or equal to zero.'])
            end
            obj.MinimumScrAmplitude = double(minimumScrAmplitude);
        end

        function output = downsampleSignal(obj,signal) %#ok<INUSD>
            %DOWNSAMPLESIGNAL Return exact-index 100 Hz EDA samples and time.
            mpk.EDAProcessor.validateSignalType(signal);
            data = eda_preprocess_signal( ...
                signal.Samples,signal.Time,signal.SamplingFrequency, ...
                'ApplyFilter',false);
            output = struct( ...
                'Eda',data.EdaDownsampled, ...
                'Time',data.Time, ...
                'SamplingFrequency',data.SamplingFrequency);
        end

        function output = filterSignal(obj,signal) %#ok<INUSD>
            %FILTERSIGNAL Delegate validated downsampling and filtering.
            mpk.EDAProcessor.validateSignalType(signal);
            output = eda_preprocess_signal( ...
                signal.Samples,signal.Time,signal.SamplingFrequency);
        end

        function decomposition = decompose(obj,signal,varargin)
            %DECOMPOSE Delegate preprocessing and cvxEDA resolution.
            mpk.EDAProcessor.validateSignalType(signal);
            options = obj.pipelineOptions(signal,varargin{:});
            preprocessed = eda_preprocess_signal( ...
                signal.Samples,signal.Time,signal.SamplingFrequency);
            decomposition = eda_resolve_decomposition( ...
                preprocessed,signal.Samples,signal.Time, ...
                signal.SamplingFrequency,options);
            eda_plot_decomposition(decomposition,options);
        end

        function features = extractFeatures(obj,signal,varargin)
            %EXTRACTFEATURES Run the canonical procedural pipeline once.
            [features,~] = obj.runPipeline(signal,varargin{:});
        end

        function result = process(obj,signal,varargin)
            %PROCESS Process exactly one complete supplied EDA Signal.
            [features,intermediates] = ...
                obj.runPipeline(signal,varargin{:});
            sourceLabel = signal.Label;
            if isempty(sourceLabel)
                sourceLabel = 'eda';
            end
            metadata = struct( ...
                'source','process_eda', ...
                'original_sampling_frequency',signal.SamplingFrequency, ...
                'processed_sampling_frequency', ...
                    intermediates.sampling_frequency, ...
                'original_n_samples',signal.count(), ...
                'processed_n_samples', ...
                    numel(intermediates.eda_downsampled), ...
                'start_time_seconds',signal.Time(1), ...
                'end_time_seconds',signal.Time(end), ...
                'cvxeda_source',intermediates.cvxeda_source, ...
                'minimum_scr_amplitude_us',obj.MinimumScrAmplitude);
            result = mpk.ProcessingResult( ...
                'eda','process_eda',features,sourceLabel, ...
                struct(),metadata);
        end
    end

    methods (Access = private)
        function [features,intermediates] = ...
                runPipeline(obj,signal,varargin)
            mpk.EDAProcessor.validateSignalType(signal);
            options = obj.pipelineOptions(signal,varargin{:});
            fullSignalPhase = [1; signal.count()];
            [features,intermediates] = eda_signal_processing( ...
                signal.Samples,signal.Time,fullSignalPhase, ...
                signal.SamplingFrequency, ...
                'CvxedaPath',options.CvxedaPath, ...
                'DecompositionCallable', ...
                    options.DecompositionCallable, ...
                'CacheDirectory',options.CacheDirectory, ...
                'OutputLabel',options.OutputLabel, ...
                'SignalLabel',options.SignalLabel, ...
                'MinimumScrAmplitude',options.MinimumScrAmplitude, ...
                'ShowPlots',options.ShowPlots, ...
                'SavePlots',options.SavePlots, ...
                'OutputDirectory',options.OutputDirectory);
        end

        function options = pipelineOptions(obj,signal,varargin)
            processing = mpk.EDAProcessor.parseProcessingOptions( ...
                varargin{:});
            outputLabel = obj.OutputLabel;
            if ~isempty(processing.OutputLabel)
                outputLabel = processing.OutputLabel;
            end
            signalLabel = signal.Label;
            if isempty(signalLabel)
                signalLabel = 'eda';
            end
            options = struct( ...
                'CvxedaPath',obj.CvxedaPath, ...
                'DecompositionCallable',obj.DecompositionCallable, ...
                'CacheDirectory',obj.CacheDirectory, ...
                'OutputLabel',outputLabel, ...
                'SignalLabel',signalLabel, ...
                'MinimumScrAmplitude',obj.MinimumScrAmplitude, ...
                'ShowPlots',processing.ShowPlots, ...
                'SavePlots',processing.SavePlots, ...
                'OutputDirectory',processing.OutputDirectory);
        end
    end

    methods (Static, Access = private)
        function validateSignalType(signal)
            if ~isa(signal,'mpk.Signal')
                error('mpk:EDAProcessor:InvalidSignal', ...
                    'signal must be an mpk.Signal instance.')
            end
        end

        function options = parseProcessingOptions(varargin)
            parser = inputParser;
            parser.FunctionName = 'mpk.EDAProcessor processing method';
            addParameter(parser,'ShowPlots',false);
            addParameter(parser,'SavePlots',false);
            addParameter(parser,'OutputDirectory','');
            addParameter(parser,'OutputLabel',[]);
            parse(parser,varargin{:});

            if ~islogical(parser.Results.ShowPlots) || ...
                    ~isscalar(parser.Results.ShowPlots)
                error('mpk:EDAProcessor:InvalidShowPlots', ...
                    'ShowPlots must be a logical scalar.')
            end
            if ~islogical(parser.Results.SavePlots) || ...
                    ~isscalar(parser.Results.SavePlots)
                error('mpk:EDAProcessor:InvalidSavePlots', ...
                    'SavePlots must be a logical scalar.')
            end
            outputDirectory = mpk.EDAProcessor.normalizeOptionalText( ...
                parser.Results.OutputDirectory,'OutputDirectory');
            outputLabel = parser.Results.OutputLabel;
            if isempty(outputLabel)
                outputLabel = [];
            else
                outputLabel = mpk.EDAProcessor.normalizeRequiredText( ...
                    outputLabel,'OutputLabel');
            end
            if parser.Results.SavePlots && isempty(outputDirectory)
                error('mpk:EDAProcessor:MissingOutputDirectory', ...
                    ['OutputDirectory must be provided when ' ...
                     'SavePlots is true.'])
            end
            options = struct( ...
                'ShowPlots',parser.Results.ShowPlots, ...
                'SavePlots',parser.Results.SavePlots, ...
                'OutputDirectory',outputDirectory, ...
                'OutputLabel',outputLabel);
        end

        function value = normalizeOptionalText(rawValue,name)
            if isempty(rawValue)
                value = '';
            elseif ischar(rawValue) && isrow(rawValue)
                value = rawValue;
            elseif isstring(rawValue) && isscalar(rawValue) && ...
                    ~ismissing(rawValue)
                value = char(rawValue);
            else
                error('mpk:EDAProcessor:InvalidConfiguration', ...
                    ['%s must be empty, a character vector, or a ' ...
                     'string scalar.'],name)
            end
        end

        function value = normalizeRequiredText(rawValue,name)
            if ischar(rawValue) && isrow(rawValue)
                value = rawValue;
            elseif isstring(rawValue) && isscalar(rawValue) && ...
                    ~ismissing(rawValue)
                value = char(rawValue);
            else
                error('mpk:EDAProcessor:InvalidConfiguration', ...
                    '%s must be a character vector or a string scalar.',name)
            end
        end
    end
end
