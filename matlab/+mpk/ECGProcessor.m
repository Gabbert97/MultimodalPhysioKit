classdef ECGProcessor
    %ECGPROCESSOR Process one complete ECG Signal analysis window.
    %
    % PROCESSOR = mpk.ECGProcessor('LabelFrequencyAnalysis',METHOD, ...
    %     'ReturnIntermediates',FLAG) configures STFT (METHOD = 1) or
    % phase-level PSD (METHOD = 2) analysis.
    %
    % RESULT = PROCESSOR.PROCESS(SIGNAL) delegates exactly once to the
    % validated ECG procedural pipeline. SIGNAL is the complete analysis
    % unit; no parent Recording or neighboring-window context is available.

    properties
        LabelFrequencyAnalysis
        ReturnIntermediates
    end

    methods
        function obj = ECGProcessor(varargin)
            parser = inputParser;
            parser.FunctionName = 'mpk.ECGProcessor';
            addParameter(parser,'LabelFrequencyAnalysis',1);
            addParameter(parser,'ReturnIntermediates',false);
            parse(parser,varargin{:});

            mpk.ECGProcessor.validateFrequencyAnalysis( ...
                parser.Results.LabelFrequencyAnalysis);
            mpk.ECGProcessor.validateReturnIntermediates( ...
                parser.Results.ReturnIntermediates);
            obj.LabelFrequencyAnalysis = ...
                parser.Results.LabelFrequencyAnalysis;
            obj.ReturnIntermediates = parser.Results.ReturnIntermediates;
        end

        function result = process(obj,signal)
            %PROCESS Process exactly one supplied mpk.Signal.
            if ~isa(signal,'mpk.Signal')
                error('mpk:ECGProcessor:InvalidSignal', ...
                    'signal must be an mpk.Signal instance.')
            end
            mpk.ECGProcessor.validateFrequencyAnalysis( ...
                obj.LabelFrequencyAnalysis);
            mpk.ECGProcessor.validateReturnIntermediates( ...
                obj.ReturnIntermediates);

            fullSignalPhase = [1; signal.count()];
            conditionColumns = 1;
            savingFlag = false;
            phaseSelectionFlag = 0;
            outputLabel = 'ecg';
            showPlots = false;

            [features,proceduralIntermediates] = ...
                ecg_signal_processing( ...
                    signal.Samples, ...
                    signal.Time, ...
                    fullSignalPhase, ...
                    conditionColumns, ...
                    signal.SamplingFrequency, ...
                    obj.LabelFrequencyAnalysis, ...
                    savingFlag, ...
                    phaseSelectionFlag, ...
                    outputLabel, ...
                    showPlots);

            if obj.ReturnIntermediates
                intermediates = mpk.ECGProcessor.unwrapIntermediates( ...
                    proceduralIntermediates,signal);
            else
                intermediates = struct();
            end

            sourceSignalLabel = signal.Label;
            if isempty(sourceSignalLabel)
                sourceSignalLabel = 'ecg';
            end
            options = struct( ...
                'LabelFrequencyAnalysis',obj.LabelFrequencyAnalysis, ...
                'ReturnIntermediates',obj.ReturnIntermediates);
            metadata = struct( ...
                'source','process_ecg', ...
                'sampling_frequency',signal.SamplingFrequency, ...
                'n_samples',signal.count(), ...
                'start_time_seconds',signal.Time(1), ...
                'end_time_seconds',signal.Time(end), ...
                'frequency_analysis_method', ...
                    obj.LabelFrequencyAnalysis, ...
                'return_intermediates',obj.ReturnIntermediates, ...
                'analysis_scope','single_signal');

            result = mpk.ProcessingResult( ...
                'ecg', ...
                'process_ecg', ...
                features, ...
                sourceSignalLabel, ...
                options, ...
                metadata, ...
                intermediates);
        end
    end

    methods (Static, Access = private)
        function validateFrequencyAnalysis(value)
            if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ...
                    ~isfinite(value) || ~any(value == [1 2])
                error('mpk:ECGProcessor:InvalidFrequencyAnalysis', ...
                    ['LabelFrequencyAnalysis must be a finite real ' ...
                     'numeric scalar equal to 1 or 2.'])
            end
        end

        function validateReturnIntermediates(value)
            if ~islogical(value) || ~isscalar(value)
                error('mpk:ECGProcessor:InvalidReturnIntermediates', ...
                    'ReturnIntermediates must be a logical scalar.')
            end
        end

        function intermediates = unwrapIntermediates(procedural,signal)
            filteredSignal = procedural.filtered_signal{1};
            candidateIndexes = procedural.candidate_r_peak_indices{1};
            candidateAmplitudes = ...
                procedural.candidate_r_peak_amplitudes{1};
            acceptedIndexes = procedural.accepted_r_peak_indices{1};
            acceptedAmplitudes = ...
                procedural.accepted_r_peak_amplitudes{1};

            intermediates = struct( ...
                'filtered_signal',filteredSignal(:), ...
                'candidate_r_peak_indices',candidateIndexes(:), ...
                'candidate_r_peak_amplitudes', ...
                    candidateAmplitudes(:), ...
                'candidate_r_peak_times', ...
                    signal.Time(candidateIndexes(:)), ...
                'accepted_r_peak_indices',acceptedIndexes(:), ...
                'accepted_r_peak_amplitudes',acceptedAmplitudes(:), ...
                'accepted_r_peak_times', ...
                    signal.Time(acceptedIndexes(:)), ...
                'ibi',procedural.ibi{1}(:), ...
                'ibi_times',procedural.ibi_times{1}(:), ...
                'bpm',procedural.bpm{1}(:), ...
                'bpm_times',procedural.bpm_times{1}(:), ...
                'frequency',procedural.frequency);

            if procedural.frequency.Method == 1
                intermediates.stft_matrix = ...
                    procedural.frequency.Matrix;
                intermediates.stft_power = ...
                    procedural.frequency.Power;
                intermediates.stft_frequencies = ...
                    procedural.frequency.Frequencies;
                intermediates.stft_times = procedural.frequency.Time;
                intermediates.stft_plf = procedural.frequency.PLF;
                intermediates.stft_phf = procedural.frequency.PHF;
                intermediates.stft_lf_hf = procedural.frequency.LFHF;
            else
                intermediates.psd = procedural.frequency.PSD{1};
                intermediates.psd_frequencies = ...
                    procedural.frequency.Frequencies{1};
            end
        end
    end
end
