function data = fnirs_preprocess_currents( ...
        signalRed,signalInfrared,time,samplingFrequency,phaseIndexes)
%FNIRS_PREPROCESS_CURRENTS Downsample and filter paired fNIRS currents.
%
% This helper centralizes the validated current preprocessing used by
% fNIRS_signal_processing. It preserves the existing moving-average
% downsampling, time shift, phase mapping, and low-pass filter.

if ~isnumeric(samplingFrequency) || ~isreal(samplingFrequency) || ...
        ~isscalar(samplingFrequency) || ~isfinite(samplingFrequency) || ...
        samplingFrequency <= 0 || mod(samplingFrequency,10) ~= 0
    error('MultimodalPhysioKit:InvalidSamplingFrequency', ...
        'fNIRS sampling frequency must be an integer multiple of 10 Hz.')
end
if ~isnumeric(signalRed) || ~isnumeric(signalInfrared) || ...
        ~isreal(signalRed) || ~isreal(signalInfrared) || ...
        ~isvector(signalRed) || ~isvector(signalInfrared)
    error('MultimodalPhysioKit:FNIRS:InvalidCurrentSignals', ...
        'fNIRS current signals must be numeric vectors.')
end
if numel(signalRed) ~= numel(signalInfrared)
    error('MultimodalPhysioKit:FNIRS:LengthMismatch', ...
        'Red and infrared fNIRS signals must have the same length.')
end
if ~isnumeric(time) || ~isreal(time) || ~isvector(time) || ...
        numel(time) ~= numel(signalRed) || any(~isfinite(time(:)))
    error('MultimodalPhysioKit:FNIRS:InvalidTime', ...
        'time must be a finite numeric vector matching the current signals.')
end
if isempty(signalRed) || any(~isfinite(signalRed(:))) || ...
        any(~isfinite(signalInfrared(:))) || any(signalRed(:) <= 0) || ...
        any(signalInfrared(:) <= 0)
    error('MultimodalPhysioKit:InvalidFnirsSignal', ...
        'fNIRS current signals must contain only positive values.')
end
if ~isnumeric(phaseIndexes) || ~isreal(phaseIndexes) || ...
        ndims(phaseIndexes) ~= 2 || size(phaseIndexes,1) ~= 2 || ...
        isempty(phaseIndexes) || any(~isfinite(phaseIndexes(:))) || ...
        any(phaseIndexes(:) ~= fix(phaseIndexes(:))) || ...
        any(phaseIndexes(:) < 1) || ...
        any(phaseIndexes(1,:) > phaseIndexes(2,:)) || ...
        any(phaseIndexes(:) > numel(signalRed))
    error('MultimodalPhysioKit:FNIRS:InvalidPhaseIndexes', ...
        ['phaseIndexes must be a nonempty 2-by-N matrix of valid ' ...
         'one-based inclusive indexes.'])
end

processedSamplingFrequency = 10;
downsamplingFactor = samplingFrequency / processedSamplingFrequency;
timeFromZero = time - time(1);

[downsampledInfrared,~,~] = downsampling( ...
    signalInfrared,timeFromZero,samplingFrequency, ...
    processedSamplingFrequency,phaseIndexes,0);
[downsampledRed,downsampledTime,processedPhaseIndexes] = downsampling( ...
    signalRed,timeFromZero,samplingFrequency, ...
    processedSamplingFrequency,phaseIndexes,0);

if processedPhaseIndexes(1,1) == 0
    processedPhaseIndexes(1,1) = 1;
end

lp = designfilt( ...
    'lowpassiir', ...
    'PassbandFrequency',0.2, ...
    'StopbandFrequency',0.4, ...
    'PassbandRipple',0.5, ...
    'StopbandAttenuation',80, ...
    'SampleRate',processedSamplingFrequency, ...
    'DesignMethod','butter');

filterOrder = 15;
paddingLength = 3 * filterOrder;
filteredRed = fnirs_zero_phase_sos( ...
    lp.Coefficients,downsampledRed,paddingLength);
filteredInfrared = fnirs_zero_phase_sos( ...
    lp.Coefficients,downsampledInfrared,paddingLength);

data = struct( ...
    'DownsampledRed',downsampledRed, ...
    'DownsampledInfrared',downsampledInfrared, ...
    'Time',downsampledTime, ...
    'PhaseIndexes',processedPhaseIndexes, ...
    'SamplingFrequency',processedSamplingFrequency, ...
    'FilteredRed',filteredRed, ...
    'FilteredInfrared',filteredInfrared, ...
    'DownsamplingFactor',downsamplingFactor);
end
