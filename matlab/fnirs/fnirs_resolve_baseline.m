function baseline = fnirs_resolve_baseline( ...
        filteredRed,filteredInfrared,samplingFrequency,phaseIndexes,varargin)
%FNIRS_RESOLVE_BASELINE Resolve self or supplied filtered-current baselines.

parser = inputParser;
parser.FunctionName = 'fnirs_resolve_baseline';
addParameter(parser,'BaselineRedValue',[]);
addParameter(parser,'BaselineInfraredValue',[]);
parse(parser,varargin{:});

redValue = parser.Results.BaselineRedValue;
infraredValue = parser.Results.BaselineInfraredValue;
redProvided = ~isempty(redValue);
infraredProvided = ~isempty(infraredValue);

if xor(redProvided,infraredProvided)
    error('MultimodalPhysioKit:FNIRS:IncompleteBaselinePair', ...
        'BaselineRedValue and BaselineInfraredValue must be supplied together.')
end

marginSeconds = 10;
if redProvided
    validateBaselineValue( ...
        redValue,'MultimodalPhysioKit:FNIRS:InvalidBaselineRedValue', ...
        'BaselineRedValue');
    validateBaselineValue( ...
        infraredValue, ...
        'MultimodalPhysioKit:FNIRS:InvalidBaselineInfraredValue', ...
        'BaselineInfraredValue');
    baseline = struct( ...
        'Mode','provided', ...
        'RedValue',redValue, ...
        'InfraredValue',infraredValue, ...
        'MarginSeconds',marginSeconds, ...
        'StartIndex',[], ...
        'EndIndex',[]);
    return
end

marginSamples = marginSeconds * samplingFrequency;
startIndex = phaseIndexes(1,1) + marginSamples;
endIndex = phaseIndexes(2,1) - marginSamples;
if endIndex < startIndex
    error('MultimodalPhysioKit:ShortFnirsBaseline', ...
        'The first fNIRS phase must exceed 20 seconds for baseline estimation.')
end

baseline = struct( ...
    'Mode','self', ...
    'RedValue',mean(filteredRed(startIndex:endIndex,1),1), ...
    'InfraredValue',mean(filteredInfrared(startIndex:endIndex,1),1), ...
    'MarginSeconds',marginSeconds, ...
    'StartIndex',startIndex, ...
    'EndIndex',endIndex);
end

function validateBaselineValue(value,errorIdentifier,argumentName)
if ~isnumeric(value) || islogical(value) || ~isreal(value) || ...
        ~isscalar(value) || ~isfinite(value) || value <= 0
    error(errorIdentifier, ...
        '%s must be a positive finite real numeric scalar.',argumentName)
end
end
