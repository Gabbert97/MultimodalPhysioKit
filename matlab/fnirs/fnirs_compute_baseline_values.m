function [baselineRedValue,baselineInfraredValue,diagnostics] = ...
        fnirs_compute_baseline_values( ...
        signalRed,signalInfrared,time,samplingFrequency)
%FNIRS_COMPUTE_BASELINE_VALUES Compute reusable filtered-current baselines.

fullSignalPhase = [1; numel(signalRed)];
currentData = fnirs_preprocess_currents( ...
    signalRed,signalInfrared,time,samplingFrequency,fullSignalPhase);
baseline = fnirs_resolve_baseline( ...
    currentData.FilteredRed,currentData.FilteredInfrared, ...
    currentData.SamplingFrequency,currentData.PhaseIndexes);

baselineRedValue = baseline.RedValue;
baselineInfraredValue = baseline.InfraredValue;
diagnostics = struct( ...
    'Mode',baseline.Mode, ...
    'RedValue',baseline.RedValue, ...
    'InfraredValue',baseline.InfraredValue, ...
    'MarginSeconds',baseline.MarginSeconds, ...
    'StartIndex',baseline.StartIndex, ...
    'EndIndex',baseline.EndIndex, ...
    'DownsampledTime',currentData.Time, ...
    'ProcessedSamplingFrequency',currentData.SamplingFrequency);
end
